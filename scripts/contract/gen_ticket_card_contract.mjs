const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, "../../contract/desk_card_contract.v2.json");

/** A ticket row with the fold's own defaults. The cases override from here, so
 *  a case says only what it is ABOUT. */
function row(over) {
  return {
    ticket_id: over.ticket_id ?? "t-0",
    type: over.type ?? "recommendation",
    state: over.state ?? "filed",
    subject: over.subject ?? "Decide this.",
    filed_for: "builder",
    filed_by: "cto",
    filed_at: "2026-08-24T00:00:00+00:00",
    trace_id: null,
    parent_id: null,
    source: "deskstore.recommendations",
    transitions: [],
    refused_transitions: [],
    terminal: over.terminal ?? false,
    next_actor: over.next_actor ?? "ceo",
    next_actor_basis: "explicit",
    next_actor_why: over.next_actor_why ?? "the row states its next actor is the ceo",
    age_hours: 40,
    age_basis: "event_timestamps",
    age_in_state_hours: over.age_in_state_hours === undefined
      ? 40 : over.age_in_state_hours,
    age_in_state_basis: over.age_in_state_basis ?? "event_timestamps",
    decided: over.decided ?? false,
    decision_count: over.decision_count ?? 0,
    decided_state: over.decided_state ?? null,
    decided_at: over.decided_at ?? null,
    decided_by: over.decided_by ?? null,
    canonical_ticket_id: null,
    decision_basis: "transitions",
    ...over,
  };
}

