/**
 * GENERATE `contract/desk_card_contract.v2.json` — the TICKET card's contract.
 *
 * WHY GENERATED AND NOT TYPED. v1's own test says it: *"generated ... never
 * typed by hand, so it cannot encode a wish."* A contract a human types is a
 * statement of intent; a contract a program emits from the code under test is
 * a statement of behaviour, and only the second one can fail.
 *
 * **AND THIS ONE GOES ONE STEP FURTHER THAN v1.** v1 is generated in
 * ClarkHarness and this repo's test asserts the fixture is internally
 * CONSISTENT WITH ITSELF — totals derived rather than retyped, a digest pinned.
 * That is the strongest thing available when the producing code lives across a
 * repo boundary. The ticket card's producing code lives HERE, in
 * `studio/desk/ticketCard.ts`, so v2's test drives the real function over every
 * case and compares. **A contract case here is an acceptance test, not a
 * fixture.**
 *
 * WHAT IS OWED AND IS NOT DONE (stated rather than quietly skipped): the
 * ClarkHarness copy. v1 is checked in to both repos byte-identical and
 * regenerated by `scripts/gen_desk_contract.py` there. **This dispatch is
 * KryptonPay-only and that repo is under review, so the ClarkHarness-side copy
 * of v2 and the generator entry that would emit it are OWED, not written.**
 * Until they exist, v2 binds one repo — which is honest, and less than v1.
 *
 * USAGE
 *   node scripts/contract/gen_ticket_card_contract.mjs          # write
 *   node scripts/contract/gen_ticket_card_contract.mjs --check  # verify only
 *
 * `--check` exits 1 if the checked-in file differs, so CI or a human can tell
 * a stale contract from a current one without reading JSON.
 */

import { createHash } from "node:crypto";
