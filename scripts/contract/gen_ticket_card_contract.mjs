const json = JSON.stringify(body, null, 1);
const digest = createHash("sha256").update(json).digest("hex");
const withDigest = JSON.stringify({ ...body, digest }, null, 1);

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch { /* absent */ }
  if (current !== withDigest) {
    console.error("STALE: contract/desk_card_contract.v2.json differs from "
      + "what this generator emits. Run it without --check and READ the diff "
      + "before updating the digest pinned in the test.");
    process.exit(1);
  }
  console.log(`current — ${cases.length} case(s), digest ${digest.slice(0, 12)}`);
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, withDigest);
  console.log(`wrote ${OUT}\n${cases.length} case(s); digest ${digest}`);
}
