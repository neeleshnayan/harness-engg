/**
 * The floor's guard rails — one test per way the room could lie.
 *
 * Run: `node --experimental-strip-types --test src/app/clark/studio/desk/floor/floorPlan.test.ts`
 *
 * The CDO spec (docs/design/CDO_AUDIT_2026-08-20.md, Deliverable B) states seven
 * acceptance criteria, each with a named falsifier. Four of them are assertions
 * about derived facts and are pinned HERE; the other three (bundle delta, theme
 * tokens, no new dependencies) are properties of the built artifact and are
 * measured on the worktree, not asserted in a unit test — stated so a reader of
 * this file does not conclude the suite covers all seven.
 *
 * The failure this file exists to make impossible: **an animated floor that
 * moves when nothing happened.** Ambient traffic on a room that claims to show
 * real traffic is the visual form of rendering an absent number as zero — it
 * reads as a busy firm and is generated by a timer.
 */

