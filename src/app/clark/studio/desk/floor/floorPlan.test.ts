/* ------------------------------------------------------------- the pulses -- */

const ev = (
  type: string, id: string, ts: string, actor: string,
  payload: Record<string, unknown>,
): SpineEvent => ({
  event_id: id, type, ts, actor, payload,
} as unknown as SpineEvent);

test("pulse count equals desk-event count, and every pulse carries a real event id", () => {
  // Criterion 4, the replay test. Its falsifier: a pulse whose event_id is not
  // in the source log, or a count that exceeds the events supplied.
  const events = [
    ev("DeskRequested", "e1", "2026-08-21T10:00:00Z", "ceo",
       { serves: "pm", subject: "review the sleeve" }),
    ev("DeskDispatched", "e2", "2026-08-21T10:01:00Z", "cto",
       { seat: "pm", task_id: "r1", task: "sleeve v2" }),
    ev("DeskRequestResolved", "e3", "2026-08-21T10:02:00Z", "cto",
       { request_id: "r1", resolution: "docs/pm/X.md" }),
    ev("DeskRecommendationDecided", "e4", "2026-08-21T10:03:00Z", "ceo",
       { seat: "pm", status: "accepted", text: "trim GLD" }),
    // Not desk traffic. Must draw nothing: the room shows the DESK's wire.
    ev("OrderApproved", "e5", "2026-08-21T10:04:00Z", "ceo", { approver: "ceo" }),
    ev("NavStruck", "e6", "2026-08-21T10:05:00Z", "system", { total_nav_usd: 2011.81 }),
  ];
  const { pulses, total } = floorPulses(events, 50);
  assert.equal(total, 4, "only the four desk event types are traffic");
  assert.equal(pulses.length, 4, "one pulse per desk event, no more and no fewer");
  const ids = new Set(events.map((e) => e.event_id));
  for (const p of pulses) {
    assert.ok(ids.has(p.eventId), `pulse ${p.eventId} has no event behind it`);
  }
  assert.equal(new Set(pulses.map((p) => p.eventId)).size, 4, "no event drawn twice");
});

test("an empty log draws an empty room — there is no ambient traffic branch", () => {
  // The single most important assertion in this file. If the floor ever grows a
  // decorative animation, this is where it shows up.
  assert.deepEqual(floorPulses([], 50), { pulses: [], total: 0 });
  assert.deepEqual(floorPulses(null, 50), { pulses: [], total: 0 });
  assert.deepEqual(floorPulses(undefined, 50), { pulses: [], total: 0 });
});

test("the drawn window is clipped newest-first and the total is reported, never implied", () => {
  const events = Array.from({ length: 30 }, (_, i) =>
    ev("DeskDispatched", `e${i}`, `2026-08-21T10:${String(i).padStart(2, "0")}:00Z`,
       "cto", { seat: "pm", task_id: `r${i}`, task: `t${i}` }));
  const { pulses, total } = floorPulses(events, 5);
  assert.equal(total, 30, "the total counts every desk event read, not the drawn window");
  assert.equal(pulses.length, 5);
  assert.deepEqual(pulses.map((p) => p.eventId), ["e29", "e28", "e27", "e26", "e25"]);
});

test("a delivery names its sender by matching the dispatch, and says so when it cannot", () => {
  // DeskRequestResolved carries {request_id, resolution, actor, trace_id} and
  // NO seat — verified on the live log 2026-08-21. Guessing a seat here would
  // draw an artifact arriving from a desk that never sent it.
  const matched = floorPulses([
    ev("DeskDispatched", "d1", "2026-08-21T09:00:00Z", "cto",
       { seat: "validator", task_id: "req-1", task: "audit" }),
    ev("DeskRequestResolved", "r1", "2026-08-21T09:30:00Z", "cto",
       { request_id: "req-1", resolution: "docs/AUDIT.md" }),
  ], 50).pulses.find((p) => p.eventId === "r1")!;
  assert.equal(matched.fromId, "validator");
  assert.equal(matched.toId, "cto");
  assert.equal(matched.verb, "delivered");
  assert.equal(matched.offFloor, null);

  const orphan = floorPulses([
    ev("DeskRequestResolved", "r2", "2026-08-21T09:30:00Z", "cto",
       { request_id: "req-missing", resolution: "docs/X.md" }),
  ], 50).pulses[0];
  assert.equal(orphan.fromId, null);
  assert.match(orphan.offFloor!, /outside the events read/);
  // It still counts. An unattributable delivery is a fact about the record.
  assert.equal(floorPulses([
    ev("DeskRequestResolved", "r2", "2026-08-21T09:30:00Z", "cto",
       { request_id: "req-missing", resolution: "docs/X.md" }),
  ], 50).total, 1);
});

test("a seat with no desk on this floor is NAMED, not dropped and not drawn as someone else", () => {
  // `cdo-trial` is a real seat on the live log with no chair in this room.
  const p = floorPulses([
    ev("DeskRecommendationDecided", "x1", "2026-08-21T11:00:00Z", "ceo",
       { seat: "cdo-trial", status: "accepted", text: "the floor spec" }),
  ], 50).pulses[0];
  assert.equal(p.fromId, "ceo");
  assert.equal(p.toId, null);
  assert.match(p.offFloor!, /cdo-trial/);
  assert.match(p.offFloor!, /no desk on this floor/);
});

test("wires group pulses without losing any — reduced motion must lose no information", () => {
  // Criterion 2's information-parity half: under the media query the moving dot
  // is replaced by a dashed aisle plus a COUNT CHIP, and the count comes from
  // here. If grouping ever dropped a pulse, the chip would under-report and the
  // reduced-motion reader would see a calmer firm than the animated one.
  const events = [
    ev("DeskDispatched", "a", "2026-08-21T10:00:00Z", "cto", { seat: "pm", task_id: "1" }),
    ev("DeskDispatched", "b", "2026-08-21T10:01:00Z", "cto", { seat: "pm", task_id: "2" }),
    ev("DeskDispatched", "c", "2026-08-21T10:02:00Z", "cto", { seat: "quant", task_id: "3" }),
    ev("DeskRecommendationDecided", "d", "2026-08-21T10:03:00Z", "ceo",
       { seat: "cdo-trial", status: "accepted" }),
  ];
  const { pulses } = floorPulses(events, 50);
  const wires = pulsesByWire(pulses);
  const onWires = wires.reduce((n, w) => n + w.pulses.length, 0);
  const offFloor = pulses.filter((p) => !p.fromId || !p.toId).length;
  assert.equal(onWires + offFloor, pulses.length,
    "every pulse is either on a wire or explicitly off-floor — none may vanish");
  const toPm = wires.find((w) => w.key === "cto>pm")!;
  assert.equal(toPm.pulses.length, 2);
});

