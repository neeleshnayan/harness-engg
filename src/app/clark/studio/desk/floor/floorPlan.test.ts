test("wires group pulses without losing any — reduced motion must lose no information", () => {
  // Criterion 2's information-parity half: under the media query the moving dot
  // is replaced by a dashed aisle plus a COUNT CHIP, and the count comes from
  // here. If grouping ever dropped a pulse, the chip would under-report and the
  // reduced-motion reader would see a calmer firm than the animated one.
  const events = [
    ev("DeskDispatched", "a", "2026-08-21T10:00:00Z", "cto", { seat: "pm", task_id: "1" }),
    ev("DeskDispatched", "b", "2026-08-21T10:01:00Z", "cto", { seat: "pm", task_id: "2" }),
    ev("DeskDispatched", "c", "2026-08-21T10:02:00Z", "cto", { seat: "quant", task_id: "3" }),
    ev("DeskRecommendationDecided", "d", "2026-08-21T10:03:00Z", "ceo",
       { seat: "cdo-trial", status: "accepted" }),
  ];
  const { pulses } = floorPulses(events, 50);
  const wires = pulsesByWire(pulses);
  const onWires = wires.reduce((n, w) => n + w.pulses.length, 0);
  const offFloor = pulses.filter((p) => !p.fromId || !p.toId).length;
  assert.equal(onWires + offFloor, pulses.length,
    "every pulse is either on a wire or explicitly off-floor — none may vanish");
  const toPm = wires.find((w) => w.key === "cto>pm")!;
  assert.equal(toPm.pulses.length, 2);
});

