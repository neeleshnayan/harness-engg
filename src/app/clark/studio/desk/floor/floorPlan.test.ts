test("the corridor walks the constitution's chain and offers NO shortcut", () => {
  assert.deepEqual([...CHAIN], ["mechanism", "adversary", "cto", "machine-room", "ceo"]);
  assert.ok(corridorHasNoShortcut(),
    "the aisle reaches a station out of chain order, or skips one — a shortcut " +
    "aisle draws a path the constitution does not have");
  // ONE polyline: every station lies ON it, and it is a single unbranched run
  // of points (no point repeats, which is what a branch would require).
  const seen = new Set(CORRIDOR.map((p) => `${p.x},${p.y}`));
  assert.equal(seen.size, CORRIDOR.length, "a repeated waypoint is a branch");
  for (const id of CHAIN) {
    const s = spotById(id)!;
    assert.ok(CORRIDOR.some((p) => p.x === s.at.x && p.y === s.at.y),
      `${id} is a chain station but the aisle does not reach it`);
  }
});

test("every corridor segment is an aisle, not a diagonal short-cut across desks", () => {
  // Two consecutive waypoints may differ on at most one axis OR be the single
  // dog-leg into the machine room. A free diagonal would let a future edit draw
  // mechanism→ceo as one straight line and still pass the ordering test above.
  let diagonals = 0;
  for (let i = 1; i < CORRIDOR.length; i++) {
    const a = CORRIDOR[i - 1], b = CORRIDOR[i];
    if (a.x !== b.x && a.y !== b.y) diagonals += 1;
  }
  assert.ok(diagonals <= 2, `${diagonals} diagonal aisle segments — the room is being cut across`);
});

