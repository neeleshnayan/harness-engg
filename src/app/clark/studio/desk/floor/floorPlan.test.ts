test("the flag is read as a LITERAL process.env member, or the browser never sees it", () => {
  // The incident this pins (builder D5, found by screenshot): `floorEnabled`
  // originally took `env = process.env` as a parameter. Next inlines
  // NEXT_PUBLIC_* only where the member access is written out literally, so in
  // the browser the injected object was empty and the room reported itself
  // "not enabled" with the flag set. A unit test cannot see webpack, so this
  // asserts on the SOURCE: the literal read must be present and must not be
  // reachable through an injected bag.
  const src = readFileSync(
    new URL("./floorPlan.ts", import.meta.url), "utf8");
  assert.match(src, /floorEnabledFrom\(process\.env\.NEXT_PUBLIC_STUDIO_FLOOR\)/,
    "the literal member access is gone — the browser will read an empty env");
  assert.doesNotMatch(src, /=\s*process\.env\s*\)/,
    "process.env is being passed as an object again; Next will not inline it");
});

