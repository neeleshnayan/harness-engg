const ev = (
  type: string, id: string, ts: string, actor: string,
  payload: Record<string, unknown>,
): SpineEvent => ({
  event_id: id, type, ts, actor, payload,
} as unknown as SpineEvent);

test("pulse count equals desk-event count, and every pulse carries a real event id", () => {
  // Criterion 4, the replay test. Its falsifier: a pulse whose event_id is not
  // in the source log, or a count that exceeds the events supplied.
  const events = [
    ev("DeskRequested", "e1", "2026-08-21T10:00:00Z", "ceo",
       { serves: "pm", subject: "review the sleeve" }),
    ev("DeskDispatched", "e2", "2026-08-21T10:01:00Z", "cto",
       { seat: "pm", task_id: "r1", task: "sleeve v2" }),
    ev("DeskRequestResolved", "e3", "2026-08-21T10:02:00Z", "cto",
       { request_id: "r1", resolution: "docs/pm/X.md" }),
    ev("DeskRecommendationDecided", "e4", "2026-08-21T10:03:00Z", "ceo",
       { seat: "pm", status: "accepted", text: "trim GLD" }),
    // Not desk traffic. Must draw nothing: the room shows the DESK's wire.
    ev("OrderApproved", "e5", "2026-08-21T10:04:00Z", "ceo", { approver: "ceo" }),
    ev("NavStruck", "e6", "2026-08-21T10:05:00Z", "system", { total_nav_usd: 2011.81 }),
  ];
  const { pulses, total } = floorPulses(events, 50);
  assert.equal(total, 4, "only the four desk event types are traffic");
  assert.equal(pulses.length, 4, "one pulse per desk event, no more and no fewer");
  const ids = new Set(events.map((e) => e.event_id));
  for (const p of pulses) {
    assert.ok(ids.has(p.eventId), `pulse ${p.eventId} has no event behind it`);
  }
  assert.equal(new Set(pulses.map((p) => p.eventId)).size, 4, "no event drawn twice");
});

test("an empty log draws an empty room — there is no ambient traffic branch", () => {
  // The single most important assertion in this file. If the floor ever grows a
  // decorative animation, this is where it shows up.
  assert.deepEqual(floorPulses([], 50), { pulses: [], total: 0 });
  assert.deepEqual(floorPulses(null, 50), { pulses: [], total: 0 });
  assert.deepEqual(floorPulses(undefined, 50), { pulses: [], total: 0 });
});

