test("the auto-policy is a caged MACHINE by the venue door, never a colleague", () => {
  const cage = spotById("autopolicy-cage");
  const venue = spotById("venue-door");
  assert.ok(cage && venue);
  assert.equal(cage!.kind, "machine");
  assert.equal(cage!.href, null, "the cage is not a door — nothing on this floor opens it");
  // "beside the venue door" is a measurable claim, so it is measured.
  const d = Math.hypot(cage!.at.x - venue!.at.x, cage!.at.y - venue!.at.y);
  assert.ok(d < 20, `the cage is ${d.toFixed(1)} units from the venue door — not beside it`);
  // Neither fixture may light: a machine is not "working".
  assert.ok(!cage!.lampable && !venue!.lampable);
});

