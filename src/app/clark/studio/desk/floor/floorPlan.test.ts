test("the camera is fixed, orthographic and dimetric — no perspective, ever", () => {
  // The spec forbids free cameras and lighting; a perspective camera would also
  // make the BACK of the room (where the approvals are) the smallest thing on
  // screen. One rotate pair, no perspective(), no scale.
  assert.ok(!CAMERA_TRANSFORM.includes("perspective"));
  assert.ok(!CAMERA_TRANSFORM.includes("scale"));
  assert.equal((CAMERA_TRANSFORM.match(/rotate/g) || []).length, 2);
});
